#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";

const rootDir = process.cwd();
loadDotEnv(path.join(rootDir, ".env"));

const args = parseArgs(process.argv.slice(2));
const outputPath = path.resolve(rootDir, args.out ?? readOptional("BABY_LOG_WRANGLER_CONFIG") ?? "wrangler.generated.toml");

const workerName = readOptional("BABY_LOG_WORKER_NAME") ?? "baby-log";
const compatibilityDate = readOptional("BABY_LOG_COMPATIBILITY_DATE") ?? "2026-04-24";
const assetsDir = readOptional("BABY_LOG_ASSETS_DIR") ?? "./dist/client";
const d1DatabaseName = readOptional("BABY_LOG_D1_DATABASE_NAME") ?? "baby_log";
const d1DatabaseId = readRequired("BABY_LOG_D1_DATABASE_ID");
const keepVars = readBoolean("BABY_LOG_KEEP_VARS", true);
const workersDev = readBoolean("BABY_LOG_WORKERS_DEV", false);
const routePattern = readOptional("BABY_LOG_ROUTE_PATTERN");
const routeZoneName = readOptional("BABY_LOG_ROUTE_ZONE_NAME");
const routeCustomDomain = readBoolean("BABY_LOG_ROUTE_CUSTOM_DOMAIN", true);

if (!workersDev && !routePattern) {
  throw new Error("Missing BABY_LOG_ROUTE_PATTERN. Set BABY_LOG_WORKERS_DEV=true only for workers.dev deployments.");
}

if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(d1DatabaseId)) {
  throw new Error("BABY_LOG_D1_DATABASE_ID must be a D1 database UUID, not the example placeholder.");
}

if (routePattern && /\bexample\.(com|org|net)\b/i.test(routePattern)) {
  throw new Error("BABY_LOG_ROUTE_PATTERN must be your real Worker route, not an example domain.");
}

const lines = [
  "# Generated by scripts/write-wrangler-config.mjs. Do not commit real deployment config.",
  `name = ${tomlString(workerName)}`,
  'main = "src/worker.ts"',
  `compatibility_date = ${tomlString(compatibilityDate)}`,
  `keep_vars = ${keepVars ? "true" : "false"}`,
];

if (workersDev) {
  lines.push("workers_dev = true");
} else if (routeZoneName) {
  lines.push("routes = [");
  lines.push(`  { pattern = ${tomlString(routePattern)}, zone_name = ${tomlString(routeZoneName)} }`);
  lines.push("]");
} else {
  lines.push("routes = [");
  lines.push(`  { pattern = ${tomlString(routePattern)}, custom_domain = ${routeCustomDomain ? "true" : "false"} }`);
  lines.push("]");
}

lines.push(
  "",
  "[assets]",
  `directory = ${tomlString(assetsDir)}`,
  'binding = "ASSETS"',
  'not_found_handling = "single-page-application"',
  "",
  "[[d1_databases]]",
  'binding = "DB"',
  `database_name = ${tomlString(d1DatabaseName)}`,
  `database_id = ${tomlString(d1DatabaseId)}`,
  'migrations_dir = "migrations"',
  "",
);

fs.writeFileSync(outputPath, `${lines.join("\n")}`);
console.log(`Wrote ${path.relative(rootDir, outputPath)}`);

function parseArgs(values) {
  const parsed = {};
  for (let index = 0; index < values.length; index += 1) {
    const value = values[index];
    if (value === "--out") {
      parsed.out = values[index + 1];
      index += 1;
    } else {
      throw new Error(`Unknown argument: ${value}`);
    }
  }
  return parsed;
}

function loadDotEnv(filePath) {
  if (!fs.existsSync(filePath)) return;
  const content = fs.readFileSync(filePath, "utf8");
  for (const rawLine of content.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (!match) continue;
    const [, key, rawValue] = match;
    if (process.env[key] !== undefined) continue;
    process.env[key] = parseEnvValue(rawValue);
  }
}

function parseEnvValue(rawValue) {
  let value = rawValue.trim();
  if ((value.startsWith('"') && value.endsWith('"')) || (value.startsWith("'") && value.endsWith("'"))) {
    value = value.slice(1, -1);
  }
  return value;
}

function readRequired(name) {
  const value = readOptional(name);
  if (!value) throw new Error(`Missing required environment variable: ${name}`);
  return value;
}

function readOptional(name) {
  const value = process.env[name];
  if (value === undefined || value.trim() === "") return null;
  return value.trim();
}

function readBoolean(name, fallback) {
  const value = readOptional(name);
  if (value === null) return fallback;
  if (["1", "true", "yes", "on"].includes(value.toLowerCase())) return true;
  if (["0", "false", "no", "off"].includes(value.toLowerCase())) return false;
  throw new Error(`${name} must be true or false`);
}

function tomlString(value) {
  return JSON.stringify(value);
}
